"""Step 2d: write METHODS.md from the recorded outputs.

Every number in METHODS.md is read from data/dem_report.json,
data/water_report.json, data/metadata.json, data/mosaic_report.json or the
scenes' MTL files, so nothing is typed in by hand.

Usage:  .venv/bin/python scripts/07_write_methods_md.py
"""

import json
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ["numpy", "rasterio", "scipy", "matplotlib"]


def pct(x, nd=2):
    return f"{100 * x:.{nd}f} %"


def main():
    dem = json.loads((ROOT / "data" / "dem_report.json").read_text())
    wr = json.loads((ROOT / "data" / "water_report.json").read_text())
    meta = json.loads((ROOT / "data" / "metadata.json").read_text())
    mosaic = json.loads((ROOT / "data" / "mosaic_report.json").read_text())
    dates = list(wr["dates"])
    res = dem["resampled"]

    L = []
    w = L.append
    w("# METHODS.md: water maps and flood extent, 2014-08-25 and 2014-09-10\n")
    w("Generated by `scripts/07_write_methods_md.py` from recorded outputs. "
      "Do not edit by hand; re-run the scripts instead. Input data are described "
      "in DATA.md.\n")
    w("```")
    w(".venv/bin/python scripts/04_dem.py             # DEM download + resampling")
    w(".venv/bin/python scripts/05_water.py           # MNDWI, masks, Otsu, water masks, checks")
    w(".venv/bin/python scripts/06_water_preview.py   # overlay previews")
    w(".venv/bin/python scripts/07_write_methods_md.py")
    w("```")
    w("Software: " + ", ".join(f"{p} {version(p)}" for p in PACKAGES) + ".\n")

    # Step 3 rules, copied verbatim from a file committed before any flood
    # area was computed.
    w((Path(__file__).parent / "step3_rules.md").read_text())

    # ---- Summary
    w("## Summary\n")
    w("| | " + " | ".join(dates) + " |")
    w("|---|" + "---|" * len(dates))
    rows = [
        ("Otsu threshold (MNDWI)", lambda d: f"{d['thresholds']['otsu']:.3f}"),
        ("Water on valley floor at Otsu (km2)", lambda d: f"{d['water_km2_floor']['otsu']:.2f}"),
        ("Valid valley-floor area (km2)", lambda d: f"{d['valid_floor_km2']:.2f}"),
        ("Valley floor masked (cloud, shadow, dilated, snow, refl <= 0)",
         lambda d: pct(d["mask_split"]["all_excluded_incl_nodata"]["floor_fraction"])),
    ]
    for name, f in rows:
        w(f"| {name} | " + " | ".join(f(wr["dates"][d]) for d in dates) + " |")
    w(f"\nValley floor (DEM <= {wr['valley_floor_max_m']:g} m): {wr['valley_floor_km2']:.2f} km2. "
      f"Masked on either date: {wr['floor_masked_on_either_date_km2']:.2f} km2 "
      f"({pct(wr['floor_masked_on_either_date_fraction'])}).\n")

    # ---- DEM
    w("## 1. Elevation (Copernicus DEM GLO-30)\n")
    w(f"- Source: {dem['stac_api']}, collection `{dem['collection']}` ({dem['collection_title']}).")
    w(f"- The catalogue describes it as follows: \"{dem['collection_description_first_sentence']}\" "
      "It is a surface model: heights include buildings and vegetation, not bare ground.")
    w(f"- Licence: `{dem['license']}`; licence document: " + ", ".join(dem["license_links"]) + ".")
    w(f"- Providers listed: {', '.join(dem['providers'])}.")
    w(f"- Vertical datum: not stated in the GeoTIFF metadata (horizontal CRS "
      f"{dem['tiles'][0]['crs']} only; tag AREA_OR_POINT = "
      f"{dem['tiles'][0]['tags'].get('AREA_OR_POINT')}). Not assumed here.\n")
    w("| Tile (STAC item) | File | Bytes | sha256 | Content-MD5 checked | Nodata in header | Min / max (m) |")
    w("|---|---|---|---|---|---|---|")
    for t in dem["tiles"]:
        w(f"| `{t['item_id']}` | `{Path(t['file']).name}` | {t['bytes']} | `{t['sha256']}` "
          f"| {'yes' if t['md5_verified'] else 'no (server sent none); size checked'} "
          f"| {t['nodata_in_file_header']} | {t['min']:.1f} / {t['max']:.1f} |")
    jg = dem["joined_grid"]
    w(f"\nThe {len(dem['tiles'])} tiles share one grid ({jg['crs']}, "
      f"{jg['transform'][0]:.10f} deg pixels) and were joined by array copy, no gaps. "
      f"**The joined DEM was then resampled with bilinear interpolation onto the "
      f"Landsat mosaic grid ({res['dst_crs']}, {res['dst_width']} x {res['dst_height']} "
      f"pixels of 30 m). This is the only resampled layer in the project.** "
      f"Result: `{res['file']}`, {res['nodata_pixels']} pixels without elevation, "
      f"range {res['min_m']} to {res['max_m']} m, median {res['median_m']} m.\n")

    # ---- MNDWI
    w("## 2. Water index (MNDWI)\n")
    d0 = wr["dates"][dates[0]]
    w("Surface reflectance = DN x scale + offset, with green scale/offset "
      f"{d0['scale_offset_green']} and SWIR1 scale/offset {d0['scale_offset_swir1']} "
      "(from DATA.md, identical for all scenes). Then "
      "MNDWI = (green - SWIR1) / (green + SWIR1), computed in float64 and saved as "
      "float32 GeoTIFFs `data/water/{pre_2014-08-25|flood_2014-09-10}_mndwi.tif` "
      "(NaN = no data or reflectance <= 0).\n")
    w("Where green or SWIR1 reflectance is <= 0, MNDWI is not meaningful (it can "
      "leave the range -1 to 1), so these pixels are masked rather than clipped or "
      "adjusted. Among them, clear valley-floor pixels with SWIR1 <= 0 but green > 0 "
      "would have MNDWI > 1, which points to water:\n")
    w("| Date | Masked for reflectance <= 0, valley floor (km2) | Of these, clear with SWIR1 <= 0, green > 0 (km2) |")
    w("|---|---|---|")
    for d in dates:
        v = wr["dates"][d]
        w(f"| {d} | {v['mask_split']['reflectance_le_0']['floor_km2']} "
          f"| {v['swir1_le0_green_gt0_clear_floor_km2']} |")
    w("")

    # ---- Masking
    w("## 3. Masking\n")
    w("Excluded using QA_PIXEL: fill (bit 0), dilated cloud (bit 1), cloud (bit 3), "
      "cloud shadow (bit 4), snow (bit 5); plus reflectance <= 0 (above). Cirrus "
      "(bit 2) is reported but **not** masked.\n")
    w("| Date | Flag | Valley floor km2 | Valley floor fraction | Floor connected to Srinagar km2 "
      "| Higher ground km2 | Higher ground fraction |")
    w("|---|---|---|---|---|---|---|")
    names = [("cloud", "cloud"), ("cloud_shadow", "cloud shadow"),
             ("dilated_cloud", "dilated cloud"), ("snow", "snow"),
             ("reflectance_le_0", "reflectance <= 0"),
             ("all_excluded_incl_nodata", "**all excluded (union, incl. no data)**"),
             ("cirrus_not_masked", "cirrus (not masked)"),
             ("cirrus_not_already_excluded", "cirrus not already excluded")]
    for d in dates:
        for key, label in names:
            s = wr["dates"][d]["mask_split"][key]
            w(f"| {d} | {label} | {s['floor_km2']} | {pct(s['floor_fraction'])} "
              f"| {s['connected_floor_km2']} | {s['higher_km2']} | {pct(s['higher_fraction'])} |")
    w("\nFlags overlap, so rows do not add up to the union. 'Higher ground' = DEM above "
      f"{wr['valley_floor_max_m']:g} m.\n")
    w("**Cirrus:** masking it as well would remove the 'cirrus not already excluded' "
      "area above. Water area at the Otsu threshold with cirrus also masked: " +
      "; ".join(f"{d}: {wr['dates'][d]['water_km2_floor_otsu_if_cirrus_masked']} km2 "
                f"(vs {wr['dates'][d]['water_km2_floor']['otsu']} km2)" for d in dates) + ".\n")
    w(f"Valley floor masked on either date: {wr['floor_masked_on_either_date_km2']} km2 "
      f"({pct(wr['floor_masked_on_either_date_fraction'])}); of the floor connected to "
      f"Srinagar: {wr['connected_floor_masked_on_either_date_km2']} km2 "
      f"({pct(wr['connected_floor_masked_on_either_date_fraction'], 3)}).\n")

    # ---- Valley floor
    w("## 4. Valley floor (analysis area)\n")
    w(f"**Analysis choice:** valley floor = pixels with resampled DEM <= "
      f"{wr['valley_floor_max_m']:g} m. File `data/water/valley_floor.tif`. Area "
      f"{wr['valley_floor_km2']} km2 ({wr['valley_floor_pixels']} pixels).\n")
    w(f"The <= {wr['valley_floor_max_m']:g} m area falls into {wr['floor_components_8conn']} "
      "separate patches (8-connected). The patch containing Srinagar (34.08 N, 74.80 E) "
      f"covers {wr['floor_connected_to_srinagar_km2']} km2; the other patches cover "
      f"{wr['floor_not_connected_to_srinagar_km2']} km2; the largest are "
      + "; ".join(f"{o['km2']} km2 centred near {o['centroid_lat_lon'][0]} N, "
                  f"{o['centroid_lat_lon'][1]} E" for o in wr["largest_other_floor_patches"])
      + ". These are low ground not joined to the Kashmir valley floor within the clip "
      "box. They are inside the analysis area as defined; the split is reported here "
      "and not applied.\n")

    # ---- Threshold
    w("## 5. Threshold (Otsu)\n")
    w(f"Otsu's method on MNDWI of valid valley-floor pixels, per date: histogram of "
      f"{wr['otsu_bins']} equal bins over [-1, 1] (width {2 / wr['otsu_bins']:g}); the "
      "threshold is the bin edge that maximises the between-class variance. "
      "Water = MNDWI > threshold.\n")
    w("| Date | Valid floor pixels | MNDWI min / median / max | Otsu | Water km2 at Otsu - "
      f"{wr['sensitivity']:g} | at Otsu | at Otsu + {wr['sensitivity']:g} | at 0 |")
    w("|---|---|---|---|---|---|---|---|")
    for d in dates:
        v = wr["dates"][d]
        t, a, m = v["thresholds"], v["water_km2_floor"], v["mndwi_valid_floor"]
        w(f"| {d} | {v['valid_floor_pixels']} | {m['min']} / {m['median']} / {m['max']} "
          f"| {t['otsu']:.3f} | {a['otsu_minus']} (t = {t['otsu_minus']:.3f}) | {a['otsu']} "
          f"| {a['otsu_plus']} (t = {t['otsu_plus']:.3f}) | {a['zero']} |")
    w("\nHistograms: `previews/mndwi_histogram_2014-08-25.png`, "
      "`previews/mndwi_histogram_2014-09-10.png`.\n")
    w("**Caution.** On 2014-09-10 the histogram has two clear peaks (land, and water near "
      "0.9) and the Otsu threshold lies between them. On 2014-08-25 water is a small "
      "fraction of the valley floor and forms a flat tail rather than a separate peak; "
      "Otsu is known to be unreliable when one class is this small, and its threshold "
      "there lies on the shoulder of the land peak. The two dates therefore have "
      "different thresholds, which matters for the flood extent in step 3.\n")

    # ---- Water masks
    w("## 6. Water masks\n")
    w("Files `data/water/{pre_2014-08-25|flood_2014-09-10}_water_mask.tif`, uint8: "
      "0 = not water, 1 = water (MNDWI > that date's Otsu threshold), 255 = masked or "
      "no data. The mask covers the whole grid; areas are counted on the valley floor "
      "only (use `valley_floor.tif`).\n")
    w("| Date | Water on valley floor (km2) | of which in patch connected to Srinagar | elsewhere |")
    w("|---|---|---|---|")
    for d in dates:
        v = wr["dates"][d]
        w(f"| {d} | {v['water_km2_floor']['otsu']} | {v['water_km2_floor_otsu_connected_to_srinagar']} "
          f"| {v['water_km2_floor_otsu_not_connected']} |")
    w(f"\nArea = pixel count x {wr['pixel_area_km2']} km2 (30 m x 30 m in UTM zone 43N map "
      "units). No correction for map-projection scale or terrain slope is applied.\n")

    # ---- Sanity
    w("## 7. Sanity checks (reported, not forced)\n")
    w(f"Box = +/- {wr['site_half_deg']} deg in latitude and longitude around each point; "
      "pixels whose centres fall inside. Water fraction is of valid pixels.\n")
    w("| Site | Point | Expected on 2014-08-25 | Date | Water | Masked | Median NDVI "
      "| MNDWI p10 / p50 / p90 | Median reflectance green / red / NIR / SWIR1 |")
    w("|---|---|---|---|---|---|---|---|---|")
    expect = {"dal_lake": "mostly water", "wular_lake": "mostly water",
              "srinagar_airport": "dry"}
    for site, pt in wr["sites"].items():
        for d in dates:
            s = wr["dates"][d]["sites"][site]
            r = s["median_reflectance"]
            w(f"| {site} | {pt[0]} N, {pt[1]} E | {expect[site]} | {d} "
              f"| {pct(s['water_fraction_of_valid'], 1)} | {pct(s['masked_fraction'], 1)} "
              f"| {s['median_ndvi']} | {' / '.join(str(x) for x in s['mndwi_p10_p50_p90'])} "
              f"| {r['green']} / {r['red']} / {r['nir']} / {r['swir1']} |")
    pre = wr["dates"][dates[0]]["sites"]
    w("\n**Result.** The airport check passes. The Dal Lake and Wular Lake checks "
      f"**fail** on {dates[0]}: {pct(pre['dal_lake']['water_fraction_of_valid'], 1)} and "
      f"{pct(pre['wular_lake']['water_fraction_of_valid'], 1)} water. In both boxes on "
      f"that date NIR reflectance is high and NDVI is {pre['dal_lake']['median_ndvi']} "
      f"and {pre['wular_lake']['median_ndvi']}, i.e. the surface in the boxes is "
      "covered by green vegetation, not open water; see "
      "`previews/water_sanity_sites.png`, where open water is visible outside the "
      "boxes. The boxes were not moved.\n")

    # ---- Seam
    w("## 8. Seam (rows 036 and 037)\n")
    w("MNDWI computed separately from each row on the mosaic grid; compared where both "
      "rows are valid and not masked (cloud, shadow, dilated cloud, snow, refl <= 0). "
      "Class uses that date's Otsu threshold.\n")
    w("| Date | Area | Pixels | MNDWI diff (036 - 037) mean / median | Mean abs diff "
      "| p1 / p99 diff | Pearson r | Class differs |")
    w("|---|---|---|---|---|---|---|---|")
    for d in dates:
        for area, s in wr["dates"][d]["seam"].items():
            m = s["mndwi_diff_036_minus_037"]
            w(f"| {d} | {area.replace('_', ' ')} | {m['pixels']} | {m['mean']} / {m['median']} "
              f"| {m['mean_abs']} | {m['p1_p99'][0]} / {m['p1_p99'][1]} | {s['pearson_r']} "
              f"| {pct(s['class_differs_fraction'], 3)} ({s['class_differs_pixels']} px) |")
    w("")

    # ---- Step 3
    fr = json.loads((ROOT / "data" / "flood_report.json").read_text())
    rs = json.loads((ROOT / "data" / "radsat_report.json").read_text())
    osm = json.loads((ROOT / "data" / "osm_report.json").read_text())
    step3(w, fr, rs, osm)

    # ---- Limitations
    w("## Limitations noted\n")
    sat = {}
    for sc in meta["scenes"].values():
        m = json.loads((ROOT / sc["mtl_file"]).read_text())["LANDSAT_METADATA_FILE"]
        a = m["IMAGE_ATTRIBUTES"]
        sat[sc["scene_id"]] = (a["SATURATION_BAND_3"], a["SATURATION_BAND_6"])
    w("- Saturation: the MTL files report saturation present (Y/N) in green (band 3) / "
      "SWIR1 (band 6) as: " + "; ".join(f"`{k}` {v[0]}/{v[1]}" for k, v in sat.items()) +
      ". QA_RADSAT was downloaded in step 3; it marks no green or SWIR1 saturation "
      "inside the clip box on either date (" + ", ".join(
          f"{d}: {v['pixels_green_saturated']} green / {v['pixels_swir1_saturated']} SWIR1 "
          "pixels" for d, v in rs["mosaics"].items()) + "). The step 2 water masks were "
      "made before QA_RADSAT was available; with no saturated pixels in the clip box "
      "they are unaffected.")
    w("- QA_PIXEL misses some small clouds (visible near the Srinagar airport box on "
      "2014-09-10, `previews/water_sanity_sites.png`). Unflagged cloud is counted as "
      "valid, not-water, and hides what is beneath it. Estimated in step 3, section U.")
    w("- The DEM is a surface model and its vertical datum is not stated in the files.")
    w("- The 2014-08-25 Otsu threshold is not well supported by its histogram (section 5); "
      "step 3 uses the 2014-09-10 threshold on both dates.")
    w("- Row 036 / 037 reflectance offsets (DATA.md) remain in the mosaic; their effect "
      "on the water class is in section 8.")
    w("- Water covered by vegetation (e.g. the Wular box on 2014-08-25) is not detected "
      "as water by MNDWI. Such areas that are open water on 2014-09-10 count as flooded.")
    w("- OpenStreetMap polygons are current (downloaded "
      f"{osm['download_started_utc']}), not a 2014 map.")
    w(f"- Mosaic grid and clip box as in DATA.md (bbox {mosaic['bbox_wgs84']}).\n")

    w("## Previews (`previews/`)\n")
    for p in ("mndwi_histogram_2014-08-25.png", "mndwi_histogram_2014-09-10.png",
              "water_srinagar_side_by_side.png", "water_valley_side_by_side.png",
              "water_sanity_sites.png", "flood_srinagar.png", "flood_valley.png"):
        w(f"- `previews/{p}`")
    w("\nWater overlays: cyan = water, magenta = masked, darkened = above "
      f"{wr['valley_floor_max_m']:g} m. Flood overlays: red = flooded, blue = persistent "
      "water, yellow = water lost, magenta = not assessed, darkened = outside the "
      "analysis area. Base image and stretch as in DATA.md.\n")

    (ROOT / "METHODS.md").write_text("\n".join(L))
    print("wrote METHODS.md")


def step3(w, fr, rs, osm):
    """Step 3 results, all read from data/flood_report.json and friends."""
    p, v, na = fr["primary"], fr["variants"], fr["not_assessed"]
    w("## Step 3 results: flood extent\n")
    w(f"Rules: `{fr['rules_file']}` (sha256 `{fr['rules_sha256']}`), reproduced above. "
      f"Analysis area: {fr['analysis_area_km2']} km2; valid on both dates: "
      f"{fr['valid_both_km2']} km2.\n")

    w("### Primary result\n")
    w(f"**Flooded area: {p['flooded_km2']} km2** (water on 2014-09-10, not water on "
      f"2014-08-25, MNDWI threshold {p['t_post']:.3f} on both dates).\n")
    w("| Class | km2 |")
    w("|---|---|")
    w(f"| Flooded | {p['flooded_km2']} |")
    w(f"| Persistent water (both dates) | {p['persistent_km2']} |")
    w(f"| Water lost (Aug water, not Sep) | {p['lost_km2']} |")
    w(f"| Water on 2014-08-25 | {p['water_pre_km2']} |")
    w(f"| Water on 2014-09-10 | {p['water_post_km2']} |")
    w(f"\nWater lost is {p['lost_km2']} km2, "
      f"{100 * p['lost_km2'] / p['water_pre_km2']:.2f} % of the August water.\n")
    w(f"Rule 4 (SWIR1 <= 0, green > 0 counted as water): "
      + "; ".join(f"{d} {k} km2" for d, k in fr["rule4_swir_le0_water_km2"].items())
      + f"; flooded pixels that are water only by rule 4: {fr['rule4_flooded_km2']} km2. "
      f"Saturated (green or SWIR1) in the analysis area: "
      + "; ".join(f"{d} {k} km2" for d, k in fr["saturated_in_area_km2"].items()) + ".\n")
    w("Files: `data/flood/flood_mask.tif` (1 = flooded, 0 = assessed and not flooded, "
      "255 = outside analysis area or not assessed), `data/flood/flood_classes.tif` "
      "(0 = not water either date, 1 = flooded, 2 = persistent, 3 = lost, 255 = outside "
      "or not assessed), `data/flood/analysis_area.tif`.\n")

    w("### Sensitivity\n")
    w("| Variant | Threshold Aug / Sep | Flooded km2 | Persistent km2 | Lost km2 |")
    w("|---|---|---|---|---|")
    rows = [("Primary (rules)", p), ("(a) each date's own Otsu", v["a_own_otsu"]),
            ("(b) 0 on both dates", v["b_zero"]),
            ("(c) 0.127 - 0.05 on both", v["c_minus_0.05"]),
            ("(c) 0.127 + 0.05 on both", v["c_plus_0.05"])]
    for name, x in rows:
        w(f"| {name} | {x['t_pre']:.3f} / {x['t_post']:.3f} | {x['flooded_km2']} "
          f"| {x['persistent_km2']} | {x['lost_km2']} |")
    w("")

    w("### Not assessed (how far the result is a lower bound)\n")
    w(f"Analysis-area pixels not valid on at least one date: **{na['km2']} km2** "
      f"({100 * na['fraction_of_area']:.3f} % of the analysis area); invalid on "
      f"2014-08-25: {na['invalid_pre_km2']} km2, on 2014-09-10: {na['invalid_post_km2']} km2. "
      "Reasons (km2, flags overlap):\n")
    keys = list(next(iter(na["reasons_km2_by_date"].values())))
    w("| Date | " + " | ".join(k.replace("_", " ") for k in keys) + " |")
    w("|---|" + "---|" * len(keys))
    for d, r in na["reasons_km2_by_date"].items():
        w(f"| {d} | " + " | ".join(str(r[k]) for k in keys) + " |")
    w("\nThis covers only masked pixels inside the analysis area. Flooding outside the "
      "analysis area (higher than 1,800 m, or low ground not connected to Srinagar) and "
      "flooding under unflagged cloud (section U) is not counted.\n")

    u = fr["unflagged_clouds"]
    w("### U. Unflagged clouds on 2014-09-10 (estimate; masks not changed)\n")
    w(f"Method as fixed in rules U1-U5. Sun azimuth {u['sun_azimuth_deg']:.2f} deg, "
      f"elevation {u['sun_elevation_deg']:.2f} deg (2014-09-10 row 036 MTL). Valid analysis "
      f"area on 2014-09-10: {u['valid_post_km2']} km2.\n")
    w("| Estimate | km2 | Flooded km2 inside |")
    w("|---|---|---|")
    w(f"| U1 QA_PIXEL medium-confidence cloud, not flagged | {u['u1_medium_conf_cloud_km2']} "
      f"| {u['u1_flooded_km2']} |")
    w(f"| U2 bright-and-white test | {u['u2_bright_white_km2']} "
      f"({100 * u['u2_fraction_of_valid']:.3f} % of valid) | {u['u2_flooded_km2']} |")
    w(f"| U3 shadow zone of U2 (upper bound) | {u['u3_shadow_zone_km2']} "
      f"| {u['u3_shadow_zone_flooded_km2']} |")
    w(f"| U3 dark part of the zone | {u['u3_dark_km2']} | {u['u3_dark_flooded_km2']} |")
    w(f"\nU4 control: the U2 test fires on {u['u4_control_bright_white_km2']} km2 "
      f"({100 * u['u4_control_fraction']:.3f} %) of the {u['u4_control_pre_clear_km2']} km2 "
      "flagged clear on 2014-08-25. The test is rough: it uses no blue or thermal band, "
      "and the shadow zone assumes cloud heights of 500 to 5,000 m.\n")

    o = fr["osm"]
    w("### OpenStreetMap water bodies and wetlands\n")
    w(f"Downloaded {osm['download_started_utc']} from {osm['endpoint']} (OSM data as of "
      f"{osm['osm_base_timestamp']}); response sha256 `{osm['response_sha256']}`, "
      f"{osm['elements']} elements, saved as `data/osm/overpass_response.json`. "
      f"{osm['licence']}.\n")
