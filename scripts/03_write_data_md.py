"""Step 1d: write DATA.md from the recorded metadata.

Every number in DATA.md is read from files written by the earlier scripts
(data/metadata.json, data/mosaic_report.json, previews/qa_summary.json) or
from the saved STAC items, so nothing is typed in by hand.

Usage:  .venv/bin/python scripts/03_write_data_md.py
"""

import json
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANDS = ["green", "red", "nir", "swir1", "qa_pixel"]
PACKAGES = ["pystac-client", "planetary-computer", "rasterio", "numpy",
            "matplotlib", "requests"]


def pct(x):
    return f"{100 * x:.2f} %"


def main():
    meta = json.loads((ROOT / "data" / "metadata.json").read_text())
    mosaic = json.loads((ROOT / "data" / "mosaic_report.json").read_text())
    qa = json.loads((ROOT / "previews" / "qa_summary.json").read_text())
    scenes = meta["scenes"]
    first = next(iter(scenes.values()))
    item = json.loads((ROOT / "data" / "raw" / f"{first['scene_id']}_stac_item.json").read_text())

    L = []
    w = L.append
    w("# DATA.md: Landsat 8 inputs for the September 2014 Kashmir flood map\n")
    w("Generated by `scripts/03_write_data_md.py` from the files the scripts "
      "wrote. Do not edit by hand; re-run the scripts instead.\n")

    w("## Source\n")
    w(f"- STAC API: {meta['stac_api']}")
    w(f"- Collection: `{meta['collection']}` (Landsat Collection 2 Level-2, "
      f"surface reflectance), DOI {item['properties'].get('sci:doi')}")
    w("- Satellite: Landsat 8 (OLI/TIRS), WRS-2 path 149, rows 036 and 037")
    w(f"- Kashmir valley clip box (WGS84): lon {mosaic['bbox_wgs84'][0]} to "
      f"{mosaic['bbox_wgs84'][2]}, lat {mosaic['bbox_wgs84'][1]} to {mosaic['bbox_wgs84'][3]}")
    sb = qa["srinagar_bbox_wgs84"]
    w(f"- Srinagar box used for previews and the cloud check (WGS84): lon {sb[0]} "
      f"to {sb[2]}, lat {sb[1]} to {sb[3]}")
    w("- Software: " + ", ".join(f"{p} {version(p)}" for p in PACKAGES) + "\n")

    w("## Reproduce\n")
    w("```")
    w("python3 -m venv .venv && .venv/bin/pip install -r requirements.txt")
    w(".venv/bin/python scripts/01_download.py      # search, download, verify")
    w(".venv/bin/python scripts/01b_mosaic.py       # grid checks, mosaic, seam check")
    w(".venv/bin/python scripts/02_preview.py       # cloud check, previews")
    w(".venv/bin/python scripts/03_write_data_md.py # this file")
    w("```")
    w("Raw files can be checked against the sha256 values below.\n")

    w("## Scenes\n")
    w("| Date | Row | Scene ID (STAC) | Landsat product ID | Acquired (UTC, STAC) "
      "| MTL date / scene centre time | Cloud cover (STAC eo:cloud_cover) "
      "| Cloud cover (MTL CLOUD_COVER / _LAND) | CRS | Pixel size | Tier |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for sc in scenes.values():
        g = sc["bands"]["red"]["grid"]
        w(f"| {sc['date']} | {sc['wrs_row']} | `{sc['scene_id']}` | `{sc['landsat_product_id']}` "
          f"| {sc['datetime_utc_stac']} | {sc['date_acquired_mtl']} {sc['scene_center_time_mtl']} "
          f"| {sc['eo_cloud_cover_stac']} % | {sc['cloud_cover_mtl']} % / {sc['cloud_cover_land_mtl']} % "
          f"| {g['crs']} | {g['transform'][0]:g} m x {-g['transform'][4]:g} m "
          f"| {sc['collection_category']} |")
    w("\nCloud cover figures are whole-scene percentages from the metadata, "
      "not for the clip box. See *Cloud check* for the valley and Srinagar.\n")
    w("The 4th date in each Landsat product ID is the USGS processing date. "
      "The scenes were not all processed on the same day; all are Collection 2, Tier 1.\n")

    w("## Band-to-file mapping, scale, offset, fill values, checksums\n")
    w("Pixel values are stored as the original integers (digital numbers, DN). "
      "Surface reflectance = DN x scale + offset. **Not applied yet.**\n")
    for name, sc in scenes.items():
        w(f"### {sc['date']} row {sc['wrs_row']}: `{sc['scene_id']}`\n")
        w(f"MTL: `{sc['mtl_file']}` sha256 `{sc['mtl_sha256']}`\n")
        w("| Band | STAC asset key | Sensor band | Raw file | Bytes | sha256 "
          "| Scale | Offset | Fill value | Fill value source |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for band in BANDS:
            b = sc["bands"][band]
            sensor = ", ".join(b["eo_band_name"]) or "-"
            if b["scale_mtl"] is not None:
                scale, offset = f"{b['scale_stac']:g}", f"{b['offset_stac']:g}"
            else:
                scale = offset = "none (bit field)"
            src = []
            if b["fill_in_file_header"] is not None:
                src.append("GeoTIFF header")
            if b["fill_in_stac"] is not None:
                src.append("STAC raster:bands nodata")
            w(f"| {band} | `{b['asset_key']}` | {sensor} | `{Path(b['raw_file']).name}` "
              f"| {b['bytes']} | `{b['sha256']}` | {scale} | {offset} "
              f"| {b['fill_value']:g} | {' and '.join(src)} |")
        w("")
    w("Scale and offset come from the STAC item's `raster:bands` and were checked "
      "to be identical to `REFLECTANCE_MULT_BAND_n` / `REFLECTANCE_ADD_BAND_n` in each "
      "scene's MTL file. Reflectance fill value 0 is in both the GeoTIFF header and "
      "STAC. The QA_PIXEL GeoTIFF has no fill value in its header; its fill value 1 "
      "comes from STAC and matches QA_PIXEL bit 0 (fill) below.\n")
    files = [b for sc in scenes.values() for b in sc["bands"].values()]
    md5 = [Path(b["raw_file"]).name for b in files if b["md5_verified"]]
    w(f"All {len(files)} band files were checked against the server's Content-Length. "
      f"The server also sent a Content-MD5 for {len(md5)} of them, and those matched: "
      + (", ".join(f"`{n}`" for n in md5) or "none") + ". The rest are the larger "
      "files, for which the server gave no MD5; the sha256 values above were "
      "computed locally after download.\n")

    w("### QA_PIXEL bit meanings (from the STAC item's classification:bitfields)\n")
    w("| Bits | Name | Values |")
    w("|---|---|---|")
    for f in item["assets"]["qa_pixel"]["classification:bitfields"]:
        bits = str(f["offset"]) if f["length"] == 1 else f"{f['offset']}-{f['offset'] + f['length'] - 1}"
        vals = ", ".join(f"{c['value']} = {c['name']}" for c in f["classes"])
        w(f"| {bits} | {f['name']} | {vals} |")
    w("")

    w("## Mosaic (rows 036 + 037)\n")
    w(f"Rule: {mosaic['mosaic_rule']}.\n")
    w("Same-pass check (STAC acquisition times):\n")
    w("| Date | Row 036 | Row 037 | Seconds apart |")
    w("|---|---|---|---|")
    for date, p in mosaic["pass_check"].items():
        w(f"| {date} | {p['row036']} | {p['row037']} | {p['seconds_apart']} |")
    g = mosaic["grid"]
    w(f"\nGrid: all four scenes and all bands use {g['crs']}, {g['pixel_size_m']:g} m "
      f"pixels, and the same grid alignment (origin offset {g['grid_origin_offset_mod_30m']} m "
      "modulo 30 m), so the mosaic is a straight pixel copy with no resampling. "
      f"Output grid: {g['width']} x {g['height']} pixels, upper-left corner "
      f"({g['transform'][2]:.0f}, {g['transform'][5]:.0f}) m. This is the smallest "
      "grid-aligned rectangle enclosing the lon/lat clip box, so it reaches slightly "
      "beyond the box. Both dates use the same grid.\n")
    w("Output files in `data/clipped/` (not committed): "
      "`{pre_2014-08-25|flood_2014-09-10}_{green|red|nir|swir1|qa_pixel}.tif`, plus "
      "`*_source.tif` recording where each pixel came from "
      "(0 = no data, 1 = row 036, 2 = row 037).\n")
    w("| Date | Pixels from row 036 | Pixels from row 037 | Pixels with only partial band data (set to fill), row 036 / 037 |")
    w("|---|---|---|---|")
    for date, d in mosaic["dates"].items():
        pb = d["pixels_partial_band_data_treated_as_invalid"]
        w(f"| {date} | {d['pixels_from_row036']} | {d['pixels_from_row037']} "
          f"| {pb['036']} / {pb['037']} |")
    w("")

    w("### Overlap comparison (seam check)\n")
    w("Pixels valid in both row 036 and row 037. Differences are row 036 minus "
      "row 037 in DN; 1 DN = 2.75e-05 reflectance.\n")
    w("Reading of these numbers: the two rows agree closely (Pearson r >= 0.99 in "
      "every band) but are not identical. There is a small systematic offset, row "
      "036 darker than row 037, clearest in red (about 110-135 DN, roughly 0.003-0.004 "
      "reflectance, in clear pixels) and SWIR1 (about 60 DN); green and NIR median "
      "offsets are under 20 DN. This is consistent with each scene being "
      "atmospherically corrected separately by USGS. The mosaic does not adjust "
      "for it, so the values step slightly at the row 036 edge.\n")
    for date, d in mosaic["dates"].items():
        o = d["overlap"]
        w(f"**{date}**: {o['pixels_valid_in_both']} overlap pixels "
          f"({o['pixels_clear_in_both']} flagged clear in both). QA_PIXEL identical in "
          f"{pct(o['qa_pixel_identical_fraction'])}; cloud bit agrees in "
          f"{pct(o['cloud_bit_agreement_fraction'])}.\n")
        w("| Pixels | Band | Identical | Mean diff | Median diff | Mean abs diff (DN) "
          "| Mean abs diff (reflectance) | 1st / 99th pct diff | Max abs diff | Pearson r |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for which, key in (("all valid", "bands_all_valid_pixels"),
                           ("clear in both", "bands_clear_pixels")):
            for band, s in o[key].items():
                w(f"| {which} | {band} | {pct(s['identical_fraction'])} "
                  f"| {s['mean_diff_dn_036_minus_037']} | {s['median_diff_dn']:g} "
                  f"| {s['mean_abs_diff_dn']} | {s['mean_abs_diff_reflectance']:.6f} "
                  f"| {s['p1_p99_diff_dn'][0]:g} / {s['p1_p99_diff_dn'][1]:g} "
                  f"| {s['max_abs_diff_dn']:g} | {s['pearson_r']} |")
        w("")

    w("### Empty area remaining\n")
    w("| Date | Empty, pixels centred in the lon/lat box | Same, row 036 alone "
      "| Empty, whole grid rectangle |")
    w("|---|---|---|---|")
    for date, d in mosaic["dates"].items():
        w(f"| {date} | {d['empty_pixels_lonlat_box']} of {d['pixels_in_lonlat_box']} px "
          f"({100 * d['empty_fraction_lonlat_box']:.4f} %) "
          f"| {pct(d['empty_fraction_row036_only_lonlat_box'])} "
          f"| {d['empty_pixels_grid_rectangle']} px "
          f"({100 * d['empty_fraction_grid_rectangle']:.4f} %) |")
    w("\nThe remaining empty pixels are scattered single pixels where one "
      "reflectance band holds the fill value 0 although the others have data "
      "(see the partial-band counts above), and the other row has no complete data "
      "there either. Every empty pixel has partial data in at least one row; none "
      "lies outside both scenes. "
      "They are left empty, not filled.\n")

    w("## Cloud check (QA_PIXEL, mosaicked data)\n")
    w("Fractions of valid (non-fill) pixels with each flag set. Flags overlap "
      "(e.g. a cloud-shadow pixel can also be flagged clear), so columns do not "
      "sum to 100 %. Srinagar comes entirely from row 036 on both dates.\n")
    w("| Date | Area | Valid pixels | Cloud (bit 3) | Cloud shadow (bit 4) | Cirrus (bit 2) "
      "| Dilated cloud (bit 1) | Cloud or shadow | Any of bits 1-4 | Snow (bit 5) | Clear (bit 6) |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    for date, areas in qa["qa_pixel"].items():
        for area in ("srinagar", "whole_valid_area"):
            s = areas[area]
            w(f"| {date} | {area.replace('_', ' ')} | {s['valid_pixels']} "
              f"| {pct(s['cloud_fraction'])} | {pct(s['cloud_shadow_fraction'])} "
              f"| {pct(s['cirrus_fraction'])} | {pct(s['dilated_cloud_fraction'])} "
              f"| {pct(s['cloud_or_shadow_fraction'])} "
              f"| {pct(s['cloud_shadow_cirrus_or_dilated_fraction'])} "
              f"| {pct(s['snow_fraction'])} | {pct(s['clear_fraction'])} |")
    w("")

    w("## Previews (`previews/`)\n")
    st = qa["stretch_2_98_percentile_raw_DN"]
    w("False colour: red = SWIR1, green = NIR, blue = Red. One shared linear "
      "stretch for all images, 2nd to 98th percentile of all valid valley pixels "
      "from both dates: " + ", ".join(f"{b} {v[0]:g} to {v[1]:g} DN" for b, v in st.items())
      + ". White = no data. The previews are for viewing only.\n")
    for p in sorted((ROOT / "previews").glob("*.png")):
        w(f"- `previews/{p.name}`")
    w("")

    (ROOT / "DATA.md").write_text("\n".join(L))
    print("wrote DATA.md")


if __name__ == "__main__":
    main()
